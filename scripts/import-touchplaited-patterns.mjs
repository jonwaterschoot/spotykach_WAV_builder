#!/usr/bin/env node
/**
 * Imports TouchPlaited's drum patterns (synth/patterns/<genre>/*.h in the
 * firmware) as the sequencer's presets: src/mangler/drumPresets.gen.ts.
 *
 *   node scripts/import-touchplaited-patterns.mjs [path/to/TouchPlaited/synth/patterns]
 *   (or: npm run import:patterns)
 *
 * Without a path it looks next to this repo (../TouchPlaited/synth/patterns).
 * Genres in the firmware's SW1 order (idm, techno, electro), files sorted by
 * name like tools/gen_patterns.py, so the presets list in the same order as
 * the hardware's S35 variants. Each step keeps its byte as authored (0xCW:
 * weight in the low nibble, chance in the high), two hex digits per step.
 */

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = resolve(process.argv[2] ?? join(ROOT, '..', 'TouchPlaited', 'synth', 'patterns'));
const OUT = join(ROOT, 'src', 'mangler', 'drumPresets.gen.ts');
const GENRES = ['idm', 'techno', 'electro'];
const TRACKS = 7, STEPS = 64;

if (!existsSync(DIR)) {
    console.error(`import-patterns: no pattern folder at ${DIR}`);
    process.exit(1);
}

/** The [7][64] table of a pattern file, as numbers. */
function parse(file) {
    const text = readFileSync(file, 'utf8').replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
    const at = text.search(/\[\s*7\s*\]\s*\[\s*64\s*\]\s*=/);
    if (at < 0) throw new Error('no [7][64] table');
    const body = text.slice(text.indexOf('{', at) + 1);
    const rows = [...body.matchAll(/\{([^{}]*)\}/g)].slice(0, TRACKS).map(m =>
        m[1].split(',').map(s => s.trim()).filter(Boolean).map(s => Number(s)));
    if (rows.length !== TRACKS || rows.some(r => r.length !== STEPS || r.some(v => !Number.isInteger(v) || v < 0 || v > 255))) {
        throw new Error(`expected ${TRACKS} rows of ${STEPS} bytes`);
    }
    return rows;
}

const presets = [];
for (const genre of GENRES) {
    const dir = join(DIR, genre);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).filter(f => f.endsWith('.h')).sort()) {
        try {
            const rows = parse(join(dir, f));
            presets.push({ genre, name: f.replace(/\.h$/, '').replace(/^\d+_/, ''), tracks: rows.map(r => r.map(v => v.toString(16).padStart(2, '0')).join('')) });
        } catch (e) {
            console.error(`import-patterns: ${genre}/${f}: ${e.message}`);
            process.exit(1);
        }
    }
}

const lines = [
    '// AUTO-GENERATED by scripts/import-touchplaited-patterns.mjs from TouchPlaited\'s',
    '// synth/patterns/<genre>/*.h. Do not edit: run `npm run import:patterns` again.',
    '//',
    '// Per track (Kick, Snare, CHH, OHH, Clap, Tom, Perc) 64 steps, two hex digits',
    '// each: 0xCW, W = weight 0–4 (more counts as 4), C = chance 0 always, 1 75%,',
    '// 2 50%, 3 25%.',
    '',
    'export const DRUM_PRESET_DATA: readonly { genre: string; name: string; tracks: readonly string[] }[] = [',
    ...presets.flatMap(p => [
        `    { genre: '${p.genre}', name: '${p.name}', tracks: [`,
        ...p.tracks.map(t => `        '${t}',`),
        '    ] },',
    ]),
    '];',
    '',
];
writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`import-patterns: wrote ${presets.length} presets to ${OUT}`);
